# 判断 AppID 是否为 UWP 应用
# UWP AppID 包含 !（包族名 + 入口点），如 Microsoft.WindowsCalculator_8wekyb3d8bbwe!App
# Win32 系统工具使用 Microsoft.AutoGenerated.{GUID} 格式，不含 !
function Is-UwpApp {
    param(
        [Parameter(Mandatory = $true)]
        [string]$AppId
    )

    return $AppId -match '!'
}

# 通过 COM 对象解析 .lnk 快捷方式的真实路径
function Resolve-ShortcutPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$LnkPath
    )

    if (-not (Test-Path -Path $LnkPath)) {
        return $null
    }

    try {
        $shell = New-Object -ComObject WScript.Shell
        $shortcut = $shell.CreateShortcut($LnkPath)
        return $shortcut.TargetPath
    }
    catch {
        return $null
    }
}

# 扫描系统开始菜单应用列表
function Get-SystemApps {
    $apps = @()

    try {
        $startApps = Get-StartApps -ErrorAction Stop
    }
    catch {
        Write-Warning "获取开始菜单应用失败: $($_.Exception.Message)"
        return @()
    }

    foreach ($app in $startApps) {
        $name = $app.Name
        $appId = $app.AppID

        if ([string]::IsNullOrWhiteSpace($name) -or [string]::IsNullOrWhiteSpace($appId)) {
            continue
        }

        if (Is-UwpApp -AppId $appId) {
            # UWP 应用：直接使用 shell:AppsFolder 启动
            $apps += [PSCustomObject]@{
                Name    = $name
                Command = "shell:AppsFolder\$appId"
                Source  = "UWP"
            }
        }
        elseif (Test-Path -Path $appId) {
            # Win32 应用且 AppID 是文件路径：直接使用
            $apps += [PSCustomObject]@{
                Name    = $name
                Command = $appId
                Source  = "Win32"
            }
        }
        else {
            # 其他情况（协议名、Microsoft.AutoGenerated 等）：使用 shell:AppsFolder 启动
            $apps += [PSCustomObject]@{
                Name    = $name
                Command = "shell:AppsFolder\$appId"
                Source  = "Shell"
            }
        }
    }

    return $apps
}

