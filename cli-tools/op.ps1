# 构建 fzf 输入：合并应用列表，生成拼音，排序
function Build-FzfInput {
    param(
        [Parameter(Mandatory = $true)]
        $SystemApps,

        [Parameter(Mandatory = $true)]
        $ConfigApps,

        $Websites,

        $LaunchCount = @{}
    )

    $allApps = @()
    if ($SystemApps) { $allApps += $SystemApps }
    if ($ConfigApps) { $allApps += $ConfigApps }

    # 合并网页条目（单网页 WebAPP： / 网页组 WebGroup：）
    if ($Websites) {
        foreach ($web in $Websites) {
            if ([string]::IsNullOrWhiteSpace($web.Name)) {
                continue
            }

            if ($null -ne $web.Urls -and ($web.Urls -is [System.Array]) -and $web.Urls.Count -gt 0) {
                # 网页组：多个 URL
                $allApps += [PSCustomObject]@{
                    Name    = "WebGroup：$($web.Name)"
                    Command = @($web.Urls)
                    Source  = "WebGroup"
                }
            }
            elseif (-not [string]::IsNullOrWhiteSpace($web.Url)) {
                # 单网页
                $allApps += [PSCustomObject]@{
                    Name    = "WebAPP：$($web.Name)"
                    Command = $web.Url
                    Source  = "Web"
                }
            }
        }
    }

    if ($allApps.Count -eq 0) {
        return @{ Lines = @(); Apps = @() }
    }

    # 检测 pypinyin 可用性
    $pypinyinAvailable = Test-Pypinyin

    # 批量转换：中文走拼音，英文缩写
    # 网页条目名称带 "WebAPP：" 或 "WebGroup：" 前缀，需去掉后再转拼音，否则前缀中的中文字符会被错误转换
    $webPrefixes = @("WebAPP：", "WebGroup：")
    $pinyinMap = @{}
    if ($pypinyinAvailable) {
        $strippedNames = @($allApps | ForEach-Object {
            $name = $_.Name
            foreach ($prefix in $webPrefixes) {
                if ($name.StartsWith($prefix)) { $name = $name.Substring($prefix.Length); break }
            }
            $name
        })
        if ($strippedNames.Count -gt 0) {
            $rawPinyinMap = ConvertTo-Pinyin -Texts $strippedNames
            # 还原为原始名称作为 key
            for ($i = 0; $i -lt $allApps.Count; $i++) {
                $origName = $allApps[$i].Name
                if ($rawPinyinMap.ContainsKey($strippedNames[$i]) -and $rawPinyinMap[$strippedNames[$i]]) {
                    $pinyinMap[$origName] = $rawPinyinMap[$strippedNames[$i]]
                }
            }
        }
    }

    # ANSI 颜色：应用名白色，拼音深灰色 #212121（黑色背景上近乎隐形）
    $esc = [char]27
    $white = "$esc[37m"
    $darkGray = "$esc[38;2;33;33;33m"
    $reset = "$esc[0m"

    # 构建 fzf 输入条目：白色名称 + 黑色拼音，附带计数
    $entries = @()
    foreach ($app in $allApps) {
        $hint = ""
        if ($pinyinMap.ContainsKey($app.Name) -and $pinyinMap[$app.Name]) {
            $hint = "  $darkGray$($pinyinMap[$app.Name])$reset"
        }
        $line = "$white$($app.Name)$reset$hint"
        $count = if ($LaunchCount.ContainsKey($app.Name)) { $LaunchCount[$app.Name] } else { 0 }
        $entries += [PSCustomObject]@{
            Line  = $line
            Name  = $app.Name
            Count = $count
        }
    }

    # 排序：先按计数降序，再按名称升序
    $entries = $entries | Sort-Object -Property @{Expression={$_.Count}; Descending=$true}, @{Expression={$_.Name}}

    return @{
        Lines = @($entries | ForEach-Object { $_.Line })
        Apps  = @($entries | ForEach-Object {
            $name = $_.Name
            $allApps | Where-Object { $_.Name -eq $name } | Select-Object -First 1
        })
    }
}

# 启动应用
function Launch-App {
    param(
        [Parameter(Mandatory = $true)]
        $Command
    )

    try {
        if ($Command -is [System.Array]) {
            # 网页组：逐个打开 URL
            foreach ($url in $Command) {
                Start-Process $url
            }
        }
        elseif ($Command -match '^https?://') {
            Start-Process $Command
        }
        elseif ($Command -match '^shell:') {
            Start-Process "explorer.exe" -ArgumentList $Command
        }
        else {
            Start-Process $Command
        }
    }
    catch {
        Write-ToolkitMessage -Kind Error -Text "启动失败: $($_.Exception.Message)"
    }
}

# 保存打开次数到配置文件
function Save-LaunchCount {
    param(
        [Parameter(Mandatory = $true)]
        [string]$AppName,

        [Parameter(Mandatory = $true)]
        [hashtable]$LaunchCount
    )

    try {
        # 更新内存计数并写入独立状态文件；配置文件不再被改写
        $currentCount = if ($LaunchCount.ContainsKey($AppName)) { $LaunchCount[$AppName] } else { 0 }
        $LaunchCount[$AppName] = $currentCount + 1

        if (-not (Write-ToolkitState -Name 'op' -Data $LaunchCount)) {
            Write-Warning '保存打开次数失败：状态文件写入失败'
        }
    }
    catch {
        Write-Warning "保存打开次数失败: $($_.Exception.Message)"
    }
}

# ============================================================
# 主逻辑
# ============================================================

# 扫描系统应用
Write-ToolkitMessage -Kind Info -Text "正在扫描应用..." -NoNewline
$systemApps = Get-SystemApps
Write-ToolkitMessage -Kind Success -Text "`r扫描完成，找到 $($systemApps.Count) 个系统应用"

# 读取配置文件
$config = Read-Config -Path $ConfigPath
$configApps = $config.Apps
$configWebsites = $config.Websites

# 构建 fzf 输入
$fzfData = Build-FzfInput -SystemApps $systemApps -ConfigApps $configApps -Websites $configWebsites -LaunchCount $config.LaunchCount

if ($fzfData.Lines.Count -eq 0) {
    Write-ToolkitMessage -Kind Warning -Text "未找到任何应用"
    exit 0
}

# 参数预搜索
if ($Search) {
    $searchLower = $Search.ToLower()
    $matchedLines = @($fzfData.Lines | Where-Object {
        $plain = $_ -replace '\x1b\[[0-9;]*m', ''
        $parts = $plain -split '  ', 2
        $nameMatch = $parts[0].ToLower().Contains($searchLower)
        $hintMatch = if ($parts.Length -gt 1) { $parts[1].Replace(' ', '').Replace('-', '').ToLower().Contains($searchLower.Replace(' ', '').Replace('-', '')) } else { $false }
        return $nameMatch -or $hintMatch
    })

    if ($matchedLines.Count -eq 1) {
        $selectedName = (($matchedLines[0] -replace '\x1b\[[0-9;]*m', '') -split '  ', 2)[0]
        $targetApp = $fzfData.Apps | Where-Object { $_.Name -eq $selectedName } | Select-Object -First 1

        if ($targetApp) {
            $sw = [System.Diagnostics.Stopwatch]::StartNew()
            Launch-App -Command $targetApp.Command
            Save-LaunchCount -AppName $targetApp.Name -LaunchCount $config.LaunchCount
            $sw.Stop()
            $displayName = $targetApp.Name -replace '^Web(APP|Group)：', ''
            Write-ToolkitMessage -Kind Info -Text "$displayName" -NoNewline
            Write-Host " 已启动，耗时 $($sw.ElapsedMilliseconds)ms"
            exit 0
        }
    }
}

# 检查 fzf 是否可用
if (-not (Get-Command fzf -ErrorAction SilentlyContinue)) {
    Write-Error "未找到 fzf.exe，请先安装 fzf"
    exit 1
}

# 调用 fzf
$fzfArgs = @(
    "--reverse",
    "--header=输入关键词搜索应用（支持拼音首字母和英文缩写），Esc 退出",
    "--exit-0",
    "--ansi"
)

if ($Search) {
    $fzfArgs += "--query=$Search"
}

$selected = $fzfData.Lines | fzf @fzfArgs

# 处理用户取消
if (-not $selected) {
    exit 0
}

# 提取选中行的名称（去除 ANSI 码后取双空格前的部分）
$selectedName = (($selected -replace '\x1b\[[0-9;]*m', '') -split '  ', 2)[0]

# 查找对应应用
$targetApp = $fzfData.Apps | Where-Object { $_.Name -eq $selectedName } | Select-Object -First 1

if ($null -eq $targetApp) {
    Write-ToolkitMessage -Kind Error -Text "未找到应用: $selectedName"
    exit 1
}

# 启动应用
$sw = [System.Diagnostics.Stopwatch]::StartNew()
Launch-App -Command $targetApp.Command
Save-LaunchCount -AppName $targetApp.Name -LaunchCount $config.LaunchCount
$sw.Stop()
$displayName = $targetApp.Name -replace '^Web(APP|Group)：', ''
Write-ToolkitMessage -Kind Info -Text "$displayName" -NoNewline
Write-Host " 已启动，耗时 $($sw.ElapsedMilliseconds)ms"
