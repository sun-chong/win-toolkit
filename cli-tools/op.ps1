<#
.SYNOPSIS
    应用快速启动

.DESCRIPTION
    通过 fzf 交互式搜索，快速启动系统应用。支持英文模糊匹配、拼音首字母和缩写搜索。

.PARAMETER Help
    显示帮助信息
    短参数：-h

.PARAMETER Search
    可选搜索关键词，匹配应用原名和拼音首字母
    唯一命中时直接启动应用，否则进入 fzf 并预填关键词

.EXAMPLE
    op
    打开 fzf 交互式搜索，选择并启动应用

.EXAMPLE
    op feishu
    搜索含 "feishu" 的应用（匹配原名和拼音首字母），
    唯一命中时直接启动，否则进入 fzf 并预填关键词

.EXAMPLE
    op -h
    显示帮助信息

.NOTES
    Author: SUNC
    Version: 1.5.0
#>

param(
    [Alias("h")]
    [switch]$Help,
    [Parameter(Position = 0)]
    [string]$Search
)

# 公共库引导：从脚本目录向上查找仓库根
$toolkitRoot = $PSScriptRoot
while ($toolkitRoot -and -not (Test-Path -LiteralPath (Join-Path $toolkitRoot 'lib\Toolkit.psd1'))) {
    $toolkitRoot = Split-Path -Parent $toolkitRoot
}
if (-not $toolkitRoot) {
    Write-Host '错误：未找到公共库 lib/Toolkit.psd1；请确认脚本位于仓库内' -ForegroundColor Red
    exit 1
}
Import-Module (Join-Path $toolkitRoot 'lib\Toolkit.psd1') -Force

# 常量
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
# 配置文件同时支持 .json 与 .jsonc，优先 .jsonc
$ConfigPath = (Resolve-ToolkitConfigPath -BasePath (Join-Path $ScriptDir "op.config")).Path

# 显示帮助
if ($Help) {
    Show-ToolkitScriptHelp -Path $MyInvocation.MyCommand.Path
    exit 0
}

