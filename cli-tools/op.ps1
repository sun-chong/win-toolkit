function ConvertTo-LaunchCount {
    param([hashtable]$State)

    $result = @{}
    foreach ($key in $State.Keys) {
        $result[$key] = [int]$State[$key]
    }
    return $result
}

# 读取 op.config.json 或 op.config.jsonc 配置文件
function Read-Config {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    if (-not (Test-Path -Path $Path)) {
        $launchCount = ConvertTo-LaunchCount -State (Read-ToolkitState -Name 'op')
        return @{ Apps = @(); Websites = @(); LaunchCount = $launchCount }
    }

    try {
        $config = Read-ToolkitJson -Path $Path

        $apps = if ($null -ne $config.apps -and ($config.apps -is [System.Array])) { $config.apps } else { @() }
        $websites = if ($null -ne $config.websites -and ($config.websites -is [System.Array])) { $config.websites } else { @() }

        # 运行时状态与配置分离：旧配置中的 launchCount 迁移到状态文件
        $launchCount = ConvertTo-LaunchCount -State (Read-ToolkitState -Name 'op')

        if ($null -ne $config.launchCount) {
            foreach ($prop in $config.launchCount.PSObject.Properties) {
                $launchCount[$prop.Name] = [int]$prop.Value
            }
            if (Write-ToolkitState -Name 'op' -Data $launchCount) {
                $config.PSObject.Properties.Remove('launchCount')
                Write-ToolkitJson -Path $Path -Data $config
            }
            else {
                Write-Warning '状态文件写入失败，保留配置文件中的 launchCount'
            }
        }

        return @{
            Apps        = $apps
            Websites    = $websites
            LaunchCount = $launchCount
        }
    }
    catch {
        Write-Warning "读取配置文件失败: $($_.Exception.Message)，已忽略配置文件"
        return @{ Apps = @(); Websites = @(); LaunchCount = @{} }
    }
}

