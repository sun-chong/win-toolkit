# 检测 pypinyin 是否可用
function Test-Pypinyin {
    try {
        $null = & python -c "import pypinyin" 2>&1
        return $LASTEXITCODE -eq 0
    }
    catch {
        return $false
    }
}

# 批量将中文文本转换为拼音首字母
function ConvertTo-Pinyin {
    param(
        [Parameter(Mandatory = $true)]
        [string[]]$Texts
    )

    $pinyinMap = @{}

    $pythonScript = @"
import sys, re
sys.stdin.reconfigure(encoding='utf-8')
sys.stdout.reconfigure(encoding='utf-8')

try:
    from pypinyin import pinyin, Style
except ImportError:
    print("错误：pypinyin 未安装，请运行以下命令安装：")
    print("pip install pypinyin")
    sys.exit(1)

def tokenize(text):
    pattern = r'[一-鿿]+|[a-zA-Z]+|[0-9]+(?:[.\-][0-9]+)*|\s+'
    return re.findall(pattern, text)

def generate_abbreviation(tokens):
    abbrev = []
    for token in tokens:
        if re.match(r'[一-鿿]+', token):
            chars = pinyin(token, style=Style.FIRST_LETTER)
            abbrev.append(''.join([c[0] for c in chars]))
        elif re.match(r'[a-zA-Z]+', token):
            abbrev.append(token[0].lower())
        elif re.match(r'[0-9]+', token):
            abbrev.append(re.sub(r'[.\-]', '', token))
    return ''.join(abbrev)

def generate_full_pinyin(tokens):
    full = []
    for token in tokens:
        if re.match(r'[一-鿿]+', token):
            # Strip tone numbers from each syllable (e.g. "chang2" -> "chang")
            chars = pinyin(token, style=Style.TONE3)
            syllables = [re.sub(r'\d+$', '', c[0]) for c in chars]
            full.append(' '.join(syllables))
        elif re.match(r'[a-zA-Z]+', token):
            full.append(token.lower())
        elif re.match(r'[0-9]+', token):
            full.append(re.sub(r'[.\-]', '', token))
    return ' '.join(full).strip()

for line in sys.stdin:
    text = line.strip()
    if not text:
        print('')
        continue
    tokens = tokenize(text)
    abbrev = generate_abbreviation(tokens)
    full = generate_full_pinyin(tokens)
    if abbrev == full:
        print(abbrev)
    else:
        print(abbrev + ' ' + full)
"@

    $inputText = $Texts -join "`n"
    $output = $inputText | & python -c $pythonScript 2>&1

    if ($LASTEXITCODE -ne 0) {
        Write-Warning "pypinyin 转换失败，将使用原始名称搜索"
        return @{}
    }

    $lines = $output -split "`n"
    for ($i = 0; $i -lt $Texts.Count; $i++) {
        $pinyin = if ($i -lt $lines.Count) { $lines[$i].Trim() } else { "" }
        $pinyinMap[$Texts[$i]] = $pinyin
    }

    return $pinyinMap
}

